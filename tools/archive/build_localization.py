"""Compile the reviewed RU/EN/KK TSV into an exportable Godot resource."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/localization/game.tsv'

def main():
    rows = {}
    spec = re.compile(r'%[0-9.]*[dfs]')
    content_sources = '\n'.join(path.read_text(encoding='utf-8') for path in sorted(SOURCE.parent.glob('*.tsv')))
    for index, line in enumerate(content_sources.splitlines(), 1):
        if not line.strip():
            continue
        cells = line.split('\t')
        assert len(cells) == 3, (index, cells)
        assert all(cells), (index, cells)
        for target in cells[1:]:
            assert spec.findall(cells[0]) == spec.findall(target), (index, cells)
        assert cells[0] not in rows, (index, cells[0])
        rows[cells[0]] = cells
    content = '\n'.join('\t'.join(row) for row in rows.values())
    (ROOT / 'assets/localization/catalog.gd').write_text(
        'extends RefCounted\n# Generated by tools/build_localization.py; edit assets/localization/*.tsv.\nconst DATA = '
        + json.dumps(content, ensure_ascii=False) + '\n', encoding='utf-8')
    sources = set()
    for path in (ROOT / 'scripts').glob('*.gd'):
        for match in re.finditer(r'"((?:[^"\\]|\\.)*)"', path.read_text(encoding='utf-8')):
            if re.search('[А-Яа-яЁё]', match[1]):
                sources.add(match[1])
    native_names = {'Русский', 'Қазақша'}
    folded = {key.casefold() for key in rows}
    missing = sorted((value for value in sources if value.casefold() not in folded and value not in native_names), key=lambda value: (len(value), value))
    (ROOT / 'artifacts/localization_missing.txt').write_text('\n'.join(missing), encoding='utf-8')
    coverage = {'entries': len(rows), 'source_literals': len(sources), 'untranslated': missing,
                'native_language_names': sorted(native_names), 'languages': ['ru', 'kk', 'en']}
    (ROOT / 'artifacts/localization_coverage.json').write_text(json.dumps(coverage, ensure_ascii=False, indent=2), encoding='utf-8')
    assert not missing, missing
    print(f'{len(rows)} translations; {len(sources)} source literals covered; no missing text.')

if __name__ == '__main__':
    main()
